// Renders docs/REPRODUCTION.md from docs/demo-run.json (written by scripts/demo.mjs) plus the
// pools and wallet balances as the chain reports them now.
//
//   node scripts/reproduction.mjs

import { readFileSync, writeFileSync } from "fs";
import { createClient } from "genlayer-js";
import { studionet } from "genlayer-js/chains";

const RPC = "https://studio.genlayer.com/api";
const run = JSON.parse(readFileSync(new URL("../docs/demo-run.json", import.meta.url), "utf8"));
const client = createClient({ chain: studionet, endpoint: RPC });
const read = (functionName, args) => client.readContract({ address: run.contract, functionName, args });
const field = (o, k) => (o instanceof Map ? o.get(k) : o[k]);
const fmt = (wei) => (Number(BigInt(String(wei))) / 1e18).toFixed(2);
const esc = (s) => String(s ?? "").replace(/\|/g, "\\|").replace(/\n/g, " ");
const tx = (h) => `[\`${h.slice(0, 10)}…\`](https://explorer-studio.genlayer.com/tx/${h})`;
const short = (a) => `${a.slice(0, 6)}…${a.slice(-4)}`;

const pools = [];
for (const [name, id] of Object.entries(run.ids)) {
  const p = await read("get_pool", [id]);
  const history = JSON.parse(field(p, "history_json"));
  const paid = history.filter((h) => h.event === "paid");
  pools.push(
    `${id} ${name.padEnd(9)} state ${field(p, "state").padEnd(7)} balance ${fmt(field(p, "balance")).padStart(6)} GEN  paid ${fmt(field(p, "total_paid"))} GEN  thresholds ${field(p, "thresholds_json")}  events ${field(p, "paid_events_json")}` +
      paid.map((h) => `\n    ${h.event_key}: ${h.split.map(([a, v]) => `${fmt(v)} GEN to ${a}…`).join(", ")}`).join("")
  );
}

const balances = [];
for (const [k, a] of Object.entries(run.accounts)) {
  const res = await fetch(RPC, {
    method: "POST",
    headers: { "content-type": "application/json" },
    body: JSON.stringify({ jsonrpc: "2.0", id: 1, method: "eth_getBalance", params: [a, "latest"] }),
  }).then((r) => r.json());
  balances.push(`${k.padEnd(10)} ${short(a)}  ${fmt(BigInt(res.result))} GEN`);
}

const rulings = run.rulings.map((r) => `| ${r.pool} | ${esc(r.label)} | **${r.verdict}** (${r.code}) | ${esc(r.why)} |`);
const rows = run.log.map((r) => {
  const result = r.refused ? `refused: ${r.refused}` : r.returned ?? "";
  return `| ${r.who} | \`${esc(r.call).slice(0, 90)}\` | ${r.value === "0" ? "" : r.value} | ${r.status} | ${r.exec} | ${esc(result).slice(0, 200)} | ${tx(r.hash)} |`;
});

const doc = `# Reproduction log (v3)

Live run of \`scripts/demo.mjs\` on GenLayer Studio against **real** GDACS events (and USGS for the earthquake), with real
validator consensus and real LLM calls. Generated by \`scripts/reproduction.mjs\` from [\`demo-run.json\`](demo-run.json).
The v2 run is kept in [\`REPRODUCTION-v2.md\`](REPRODUCTION-v2.md).

- Contract: [\`${run.contract}\`](https://explorer-studio.genlayer.com/address/${run.contract})
  (\`node scripts/verify-code.mjs ${run.contract}\` prints \`identical\`: the deployed code is \`contracts/relief_trigger.py\`).
- Throwaway accounts: ${Object.entries(run.accounts).map(([k, a]) => `${k} \`${a}\``).join(", ")}.
- Pool names, terms and recipient wallets are written for the test; the events and every fact the validators read are
  real GDACS and USGS records.

## Rulings and the reason stored with each

| Pool | Event | Ruling | Reason (on-chain \`claim_why\`) |
|---|---|---|---|
${rulings.join("\n")}

## Final state

\`\`\`
${pools.join("\n")}
\`\`\`

Wallet balances after finalization. The wildfire recipients started with 1 GEN each and received 3.00 / 1.80 / 1.20
GEN (50 / 30 / 20% of the 6 GEN payout for the 19,294 ha Spanish fire); the earthquake recipients received 2.80 / 1.20
GEN (70 / 30% of 4 GEN).

\`\`\`
${balances.join("\n")}
\`\`\`

## Every transaction

A refused call is still ACCEPTED by consensus; the contract outcome is the \`exec\` column (\`ERROR\` = the contract raised,
on purpose here). Payable calls never raise: they return \`REFUNDED: <reason>\` and send the GEN back, because GenLayer
keeps the value of a reverted call.

| Who | Call | GEN sent | Consensus | Exec | Returned / refused | Tx |
|---|---|---|---|---|---|---|
${rows.join("\n")}

## Run it yourself

\`\`\`bash
npm install
node scripts/deploy.mjs                      # prints the new contract address
node scripts/verify-code.mjs <address>       # deployed code == contracts/relief_trigger.py
node scripts/demo.mjs <address>              # about 10 minutes
node scripts/reproduction.mjs                # regenerates this file
\`\`\`
`;

writeFileSync(new URL("../docs/REPRODUCTION.md", import.meta.url), doc);
console.log(`wrote docs/REPRODUCTION.md (${run.log.length} transactions, ${run.rulings.length} rulings)`);
